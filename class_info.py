def get_all_descriptions() -> dict[str, str]:
    result = {}
    for cls, info in CLASS_INFO.items():
        parts = [
            info.get("what_includes", ""),
            info.get("course", ""),
            info.get("age_group", ""),
            " ".join(info.get("clinical_signs", [])),
            info.get("ml_notes", ""),
        ]
        result[cls] = " ".join(p for p in parts if p)
    return result